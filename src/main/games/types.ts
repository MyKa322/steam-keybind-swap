/**
 * Описание игры: какие файлы в userdata/<account>/<appid> относятся к настройкам
 * и на какие смысловые группы они делятся.
 *
 * Добавить поддержку новой игры = добавить сюда профиль и зарегистрировать его
 * в registry.ts. Логику копирования, бэкапов и remotecache трогать не нужно.
 */

export interface FileGroup {
  id: string
  /** Ключи словаря i18n — подписи живут в renderer, main их не знает */
  labelKey: string
  descriptionKey: string
  defaultEnabled: boolean
  /** Предупреждение о специфике группы, например «привязано к железу» */
  advisoryKey?: string
  /**
   * Пути относительно папки <appid>, через прямой слэш.
   * В имени файла допускается `*` — он раскрывается только внутри одного
   * сегмента пути, поэтому `cfg/*.build` не заглянет в подпапки.
   */
  patterns: string[]
}

export interface GameProfile {
  appId: string
  name: string
  /** Имена процессов игры — их наличие блокирует перенос (игра перезапишет конфиг при выходе) */
  processNames: string[]
  groups: FileGroup[]
  /**
   * Файлы, которые нельзя копировать ни при каких условиях. Проверяется
   * последним, уже после раскрытия шаблонов групп — то есть перекрывает их.
   */
  denyPatterns: string[]
}

/** Служебные файлы Steam Cloud, общие для всех игр на Source 2. */
export const COMMON_DENY_PATTERNS = [
  // Манифест облака — мы его патчим отдельно и осознанно, копировать нельзя
  'remotecache.vdf',
  // Слепок последней успешной синхронизации: подмена собьёт Steam с толку
  '*/*_lastclouded',
  '*/*/*_lastclouded',
  '*.bak',
  '*/*.bak',
  '*/*/*.bak'
]
